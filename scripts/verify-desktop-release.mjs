// Native release gate. Uses only generated artifacts and private synthetic data;
// it never connects to a backend or modifies an installed agent profile.
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import crypto from "node:crypto";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { verifyDesktopUi } from "./verify-desktop-ui.mjs";

const require = createRequire(import.meta.url);
const { extractFile } = require("@electron/asar");
const repository = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const readJson = filename => JSON.parse(fs.readFileSync(filename, "utf8"));
const desktop = readJson(path.join(repository, "apps/desktop/package.json"));
const expected = desktop.version;
assert.equal(readJson(path.join(repository, "apps/agent/package.json")).version, expected);
const lock = readJson(path.join(repository, "package-lock.json"));
for (const workspace of ["apps/agent", "apps/desktop"]) assert.equal(lock.packages[workspace].version, expected);
assert.equal(fs.readFileSync(path.join(repository, "apps/agent/src/index.ts"), "utf8").match(/const AGENT_VERSION = "([^"]+)"/)?.[1], expected);
if (process.env.GITHUB_REF_NAME?.startsWith("desktop-v")) assert.equal(process.env.GITHUB_REF_NAME, `desktop-v${expected}`);
assert.ok(["darwin", "win32"].includes(process.platform), "Run this gate on the native Windows or macOS builder.");
const platform = process.platform === "darwin" ? "mac" : "win";
const release = path.join(repository, "apps/desktop/release");
const zip = path.join(release, `DriveOS-Agent-${platform}.zip`);
const installer = path.join(release, `DriveOS-Agent-${platform}.${platform === "mac" ? "dmg" : "exe"}`);
for (const filename of [zip, installer]) assert.ok(fs.statSync(filename).size > 0, `Missing release artifact: ${filename}`);
const digest = filename => crypto.createHash("sha256").update(fs.readFileSync(filename)).digest("hex");
const expectedBundleHash = digest(path.join(repository, "apps/agent/dist/agent-bundle.cjs"));
const tempRoot = path.resolve(process.env.RUNNER_TEMP || os.tmpdir());
const fixture = fs.mkdtempSync(path.join(tempRoot, "driveos-release-verify-"));
const unpacked = path.join(fixture, "zip");
const mount = path.join(fixture, "dmg");
let mounted = false;
function run(binary, args, options = {}) {
  return execFileSync(binary, args, { encoding: "utf8", timeout: 120_000, maxBuffer: 32 * 1024 * 1024,
    windowsHide: true, ...options });
}
function application(directory, depth = 0) {
  const direct = platform === "mac" ? fs.readdirSync(directory).find(name => name.endsWith(".app"))
    : fs.existsSync(path.join(directory, "DriveOS Agent.exe")) ? "" : undefined;
  if (direct !== undefined) return direct ? path.join(directory, direct) : directory;
  if (depth < 2) {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      if (entry.isDirectory()) { const found = application(path.join(directory, entry.name), depth + 1); if (found) return found; }
    }
  }
  return undefined;
}
function inspect(app) {
  assert.ok(app, "Extracted artifact must contain the application.");
  const resources = platform === "mac" ? path.join(app, "Contents/Resources") : path.join(app, "resources");
  const executable = platform === "mac" ? path.join(app, "Contents/MacOS/DriveOS Agent") : path.join(app, "DriveOS Agent.exe");
  const archive = path.join(resources, "app.asar");
  const packageJson = JSON.parse(extractFile(archive, "package.json").toString("utf8"));
  assert.equal(packageJson.version, expected, "Packaged desktop version must match its tag and source.");
  const bundle = path.join(resources, "agent/agent-bundle.cjs");
  assert.equal(digest(bundle), expectedBundleHash, "Packaged agent must be the bundle generated by this build.");
  if (platform === "mac") {
    assert.equal(run("plutil", ["-extract", "CFBundleShortVersionString", "raw", "-o", "-", path.join(app, "Contents/Info.plist")]).trim(), expected);
    for (const binary of [executable, path.join(app, "Contents/Frameworks/Electron Framework.framework/Versions/A/Electron Framework")]) {
      const architectures = run("lipo", ["-archs", binary]).trim().split(/\s+/);
      for (const architecture of ["x86_64", "arm64"]) assert.ok(architectures.includes(architecture), `${binary} must contain ${architecture}`);
    }
  }
  return { executable, bundle, archiveHash: digest(archive) };
}
function findFile(directory, basename, depth = 0) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    if (entry.isFile() && entry.name === basename) return path.join(directory, entry.name);
    if (entry.isDirectory() && depth < 4) {
      const found = findFile(path.join(directory, entry.name), basename, depth + 1);
      if (found) return found;
    }
  }
  return undefined;
}
function nsisExtractor() {
  const candidates = [path.join(process.env.ProgramFiles || "C:\\Program Files", "7-Zip/7z.exe"),
    "7z.exe", require("7zip-bin").path7za];
  for (const candidate of candidates) {
    try { if (/\bnsis\b/i.test(run(candidate, ["i"]))) return candidate; } catch { /* Try the next installed binary. */ }
  }
  throw new Error("NSIS verification requires an installed full 7-Zip binary with the NSIS format enabled.");
}
try {
  fs.mkdirSync(unpacked);
  if (platform === "mac") run("ditto", ["-x", "-k", zip, unpacked]);
  else run("powershell.exe", ["-NoProfile", "-NonInteractive", "-Command",
    "Expand-Archive -LiteralPath $env:DRIVEOS_VERIFY_ZIP -DestinationPath $env:DRIVEOS_VERIFY_DEST -Force"],
    { env: { ...process.env, DRIVEOS_VERIFY_ZIP: zip, DRIVEOS_VERIFY_DEST: unpacked } });
  const packaged = inspect(application(unpacked));
  const home = path.join(fixture, "agent-home"), media = path.join(fixture, "media");
  fs.mkdirSync(media);
  const env = { ...process.env, ELECTRON_RUN_AS_NODE: "1", DRIVEOS_AGENT_HOME: home,
    DRIVEOS_CONVEX_URL: "http://127.0.0.1:9", TEMP: fixture, TMP: fixture, TMPDIR: fixture };
  const cli = (...args) => run(packaged.executable, [packaged.bundle, ...args], { cwd: fixture, env }).trim();
  assert.equal(cli("--version"), expected, "The packaged runtime must execute this agent version.");
  cli("init", "--machine", "ReleaseSmoke", "--owner", "synthetic", "--convex", "http://127.0.0.1:9",
    "--roots", media, "--central-quarantine", "--quarantine", path.join(fixture, "quarantine"));
  const status = () => JSON.parse(cli("status", "--json"));
  assert.equal(status().machineName, "ReleaseSmoke");
  assert.equal(path.resolve(status().appDataDir), path.resolve(home));
  cli("pause"); assert.equal(status().paused, true);
  cli("resume"); assert.equal(status().paused, false);
  if (process.env.GITHUB_ACTIONS === "true" && process.env.RUNNER_TEMP) {
    await verifyDesktopUi({ executable: packaged.executable, fixture, home, env, release, platform, version: expected });
  }
  const tests = ["fileOperations", "operationJournal", "scanLock", "keepCopy", "watchQueue", "manifestFiles", "backendHttp", "scanExit"]
    .map(name => path.join(repository, `apps/agent/dist/${name}.test.js`));
  tests.push(path.join(repository, "scripts/desktop-agent.test.mjs"));
  for (const filename of tests) assert.ok(fs.existsSync(filename), "Compile the agent regression tests before this gate.");
  const testOutput = run(packaged.executable, ["--test", ...tests], {
    cwd: fixture, env: { ...env, DRIVEOS_TEST_AGENT_ENTRY: packaged.bundle },
  });
  // A zero exit code with no test output is not evidence that Electron ran
  // the Node test runner. Require an actual completed TAP summary.
  assert.ok(Number(testOutput.match(/^# tests (\d+)\r?$/m)?.[1]) > 0, "The packaged runtime must execute the native and scan-exit tests.");
  assert.ok(Number(testOutput.match(/^# pass (\d+)\r?$/m)?.[1]) > 0, "The packaged runtime must report passing tests.");
  assert.match(testOutput, /^# fail 0\r?$/m);
  assert.match(testOutput, /^# cancelled 0\r?$/m);
  process.stdout.write(testOutput);
  if (platform === "mac") {
    fs.mkdirSync(mount);
    run("hdiutil", ["attach", "-readonly", "-nobrowse", "-mountpoint", mount, installer]);
    mounted = true;
    const dmg = inspect(application(mount));
    assert.equal(dmg.archiveHash, packaged.archiveHash, "DMG and ZIP must contain identical desktop application metadata/code.");
    assert.equal(run(dmg.executable, [dmg.bundle, "--version"], { cwd: fixture, env }).trim(), expected);
  } else {
    const sevenZip = nsisExtractor();
    const nsis = path.join(fixture, "nsis"), payload = path.join(fixture, "nsis-payload");
    fs.mkdirSync(nsis); fs.mkdirSync(payload);
    run(sevenZip, ["x", "-tNsis", "-y", `-o${nsis}`, installer]);
    const archive = findFile(nsis, "app-64.7z");
    assert.ok(archive, "NSIS installer must contain its x64 application archive.");
    run(sevenZip, ["x", "-y", `-o${payload}`, archive]);
    const installed = inspect(application(payload));
    assert.equal(installed.archiveHash, packaged.archiveHash, "NSIS and ZIP must contain identical desktop application metadata/code.");
    assert.equal(run(installed.executable, [installed.bundle, "--version"], { cwd: fixture, env }).trim(), expected);
  }
  console.log(JSON.stringify({ version: expected, platform, runtimeArchitecture: process.arch,
    packagedAgentSha256: expectedBundleHash, artifacts: [zip, installer].map(filename => ({ name: path.basename(filename), sha256: digest(filename) })) }));
} finally {
  if (mounted) run("hdiutil", ["detach", mount]);
  assert.equal(path.dirname(path.resolve(fixture)), tempRoot);
  fs.rmSync(fixture, { recursive: true, force: true });
}
